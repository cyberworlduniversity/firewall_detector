# ─────────────────────────────────────────────
# CORE DETECTION ENGINE
# ─────────────────────────────────────────────
class FirewallDetector:
    def __init__(self, target: str, timeout: int = 10, verbose: bool = False):
        self.target = self._normalize_url(target)
        self.timeout = timeout
        self.verbose = verbose
        self.results = {
            "target": self.target,
            "scan_time": datetime.now().isoformat(),
            "waf_detected": False,
            "waf_names": [],
            "confidence": "None",
            "evidence": [],
            "response_codes": {},
            "headers_found": {},
            "probe_results": [],
        }
        self.session = requests.Session()
        self.session.headers.update({
            "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) "
                          "AppleWebKit/537.36 (KHTML, like Gecko) "
                          "Chrome/120.0.0.0 Safari/537.36",
            "Accept": "text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8",
            "Accept-Language": "en-US,en;q=0.5",
        })

    def _normalize_url(self, url: str) -> str:
        if not url.startswith(("http://", "https://")):
            url = "https://" + url
        return url.rstrip("/")

    def _get(self, url: str) -> requests.Response | None:
        try:
            # Keep Requests' default certificate and hostname verification enabled.
            return self.session.get(url, timeout=self.timeout, allow_redirects=True)
        except requests.exceptions.SSLError as e:
            if self.verbose:
                cprint(Colors.RED, f"  [!] TLS verification failed: {e}")
            return None
        except Exception as e:
            if self.verbose:
                cprint(Colors.RED, f"  [!] Request error: {e}")
            return None

    def _check_signatures(self, response: requests.Response) -> list:
        detected = []
        resp_headers = {k.lower(): v.lower() for k, v in response.headers.items()}
        resp_cookies = {k.lower(): v.lower() for k, v in response.cookies.items()}
        resp_body    = response.text.lower() if response.text else ""
        server_val   = resp_headers.get("server", "")

        for waf_name, sigs in WAF_SIGNATURES.items():
            score = 0
            evidence = []

            # Check headers
            for hdr in sigs["headers"]:
                if hdr.lower() in resp_headers:
                    score += 3
                    evidence.append(f"Header: {hdr}={resp_headers[hdr.lower()][:60]}")

            # Check cookies
            for ck in sigs["cookies"]:
                for cookie_key in resp_cookies:
                    if ck.lower() in cookie_key:
                        score += 3
                        evidence.append(f"Cookie: {cookie_key}")

            # Check body keywords
            for kw in sigs["body_keywords"]:
                if kw.lower() in resp_body:
                    score += 2
                    evidence.append(f"Body keyword: '{kw}'")

            # Check server header
            for sv in sigs["server_values"]:
                if sv.lower() in server_val:
                    score += 4
                    evidence.append(f"Server: {server_val}")

            if score >= 2:
                detected.append({
                    "waf": waf_name,
                    "score": score,
                    "evidence": evidence
                })

        return sorted(detected, key=lambda x: x["score"], reverse=True)

    def _probe_with_payloads(self) -> list:
        probe_results = []
        cprint(Colors.YELLOW, "\n[*] Probing with attack-like payloads...")

        for payload in PROBE_PAYLOADS:
            url = self.target + payload
            resp = self._get(url)
            if resp is None:
                probe_results.append({"payload": payload, "status": "error", "code": None})
                continue

            code = resp.status_code
            blocked = code in [400, 403, 406, 429, 503]
            probe_results.append({
                "payload": payload,
                "status": "BLOCKED" if blocked else "ALLOWED",
                "code": code
            })

            status_color = Colors.RED if blocked else Colors.GREEN
            cprint(status_color,
                   f"  {'🚫 BLOCKED' if blocked else '✅ ALLOWED'} [{code}] {payload}")
            time.sleep(0.5)

        return probe_results

    def run(self) -> dict:
        banner()
        cprint(Colors.BLUE, f"[*] Target  : {self.target}")
        cprint(Colors.BLUE, f"[*] Started : {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n")

        # ── Step 1: Normal request
        cprint(Colors.CYAN, "[*] Sending baseline request...")
        resp = self._get(self.target)
        if resp is None:
            cprint(Colors.RED, "[!] Could not reach target. Exiting.")
            self.results["error"] = "Unreachable"
            return self.results

        self.results["response_codes"]["baseline"] = resp.status_code
        self.results["headers_found"] = dict(resp.headers)

        if self.verbose:
            cprint(Colors.WHITE, f"  Status : {resp.status_code}")
            cprint(Colors.WHITE, f"  Server : {resp.headers.get('Server', 'N/A')}")

        # ── Step 2: Signature matching
        cprint(Colors.CYAN, "\n[*] Running WAF signature analysis...")
        matches = self._check_signatures(resp)

        if matches:
            self.results["waf_detected"] = True
            for m in matches:
                self.results["waf_names"].append(m["waf"])
                self.results["evidence"].extend(m["evidence"])

            top = matches[0]
            self.results["confidence"] = (
                "High"   if top["score"] >= 6 else
                "Medium" if top["score"] >= 3 else
                "Low"
            )

        # ── Step 3: Payload probing
        self.results["probe_results"] = self._probe_with_payloads()
        blocked_count = sum(1 for p in self.results["probe_results"]
                            if p.get("status") == "BLOCKED")

        if blocked_count >= 2 and not self.results["waf_detected"]:
            self.results["waf_detected"] = True
            self.results["waf_names"].append("Unknown WAF")
            self.results["confidence"] = "Medium"
            self.results["evidence"].append(
                f"Blocked {blocked_count}/4 attack probes"
            )

        # ── Step 4: Print report
        self._print_report(blocked_count)
        return self.results

    def _print_report(self, blocked_count: int):
        print(f"\n{Colors.BOLD}{Colors.WHITE}{'═'*56}")
        print("               📊  SCAN REPORT")
        print(f"{'═'*56}{Colors.RESET}")

        if self.results["waf_detected"]:
            waf_list = ", ".join(set(self.results["waf_names"]))
            cprint(Colors.RED,    f"  🧱 WAF DETECTED     : YES")
            cprint(Colors.YELLOW, f"  🔍 WAF Name(s)      : {waf_list}")
            cprint(Colors.YELLOW, f"  📶 Confidence       : {self.results['confidence']}")
        else:
            cprint(Colors.GREEN, "  ✅ WAF DETECTED     : NO (or undetected)")

        cprint(Colors.WHITE, f"  🌐 Target           : {self.target}")
        cprint(Colors.WHITE, f"  🚫 Probes Blocked   : {blocked_count}/4")

        if self.results["evidence"]:
            print(f"\n{Colors.CYAN}  📌 Evidence:{Colors.RESET}")
            for ev in set(self.results["evidence"])[:10]:
                print(f"     • {ev}")

        print(f"{Colors.BOLD}{Colors.WHITE}{'═'*56}{Colors.RESET}\n")

    def save_json(self, filename: str = None):
        if not filename:
            domain = urlparse(self.target).netloc.replace(".", "_")
            filename = f"waf_report_{domain}_{int(time.time())}.json"
        with open(filename, "w") as f:
            json.dump(self.results, f, indent=4)
        cprint(Colors.GREEN, f"[+] Report saved → {filename}")
        return filename


# ─────────────────────────────────────────────
# CLI ENTRY POINT
# ─────────────────────────────────────────────
def main():
    parser = argparse.ArgumentParser(
        description="🧱 Firewall Detector - WAF Detection Tool | GitHub: hemanathan115",
        formatter_class=argparse.RawTextHelpFormatter,
        epilog="""
Examples:
  python firewall_detector.py -u example.com
  python firewall_detector.py -u https://example.com -v
  python firewall_detector.py -u example.com --save
  python firewall_detector.py -u example.com --timeout 15 --save
        """
    )
    parser.add_argument("-u", "--url",     required=True, help="Target URL or domain")
    parser.add_argument("-v", "--verbose", action="store_true", help="Verbose output")
    parser.add_argument("--timeout",       type=int, default=10, help="Request timeout (default: 10s)")
    parser.add_argument("--save",          action="store_true", help="Save JSON report")
    parser.add_argument("--output",        help="Custom output filename for JSON report")
    args = parser.parse_args()

    detector = FirewallDetector(args.url, timeout=args.timeout, verbose=args.verbose)
    results  = detector.run()

    if args.save or args.output:
        detector.save_json(args.output)

    sys.exit(0 if not results.get("error") else 1)

if __name__ == "__main__":
    main()
